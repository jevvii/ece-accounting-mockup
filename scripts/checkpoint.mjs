#!/usr/bin/env node
// Dependency-free continuation checkpoint for the ECE Accounting mockup.
// Validates docs/STATE.json, fingerprints relevant sources, writes STATE
// atomically (temp file + rename) and regenerates HANDOFF.md from STATE.
// Fingerprinting is evidence of which sources a verification run covered; it
// does not prove that tests passed.

import { createHash } from 'node:crypto';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STATE_PATH = path.join(ROOT, 'docs', 'STATE.json');
const HANDOFF_PATH = path.join(ROOT, 'HANDOFF.md');
const TODO_PATH = path.join(ROOT, 'tasks', 'todo.md');

const FINGERPRINT_DIRS = ['src', 'tests', 'benchmark', 'scripts', 'fixtures', '.github'];
const FINGERPRINT_FILES = [
  'package.json',
  'package-lock.json',
  '.gitignore',
  'tsconfig.json',
  'vite.config.ts',
  'playwright.config.ts',
  'playwright.benchmark.config.ts',
  'index.html',
  'AGENTS.md',
  'CLAUDE.md',
  'docs/BUSINESS-RULES.md',
];
const IGNORED_DIRS = new Set(['node_modules', 'dist', 'artifacts', '.git', 'test-results', 'playwright-report']);

function fail(message) {
  console.error(`checkpoint: ${message}`);
  process.exitCode = 1;
  throw new Error(message);
}

async function walk(relativeDir, files) {
  const absolute = path.join(ROOT, relativeDir);
  let entries;
  try {
    entries = await fs.readdir(absolute, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') return;
    throw error;
  }
  for (const entry of entries) {
    if (IGNORED_DIRS.has(entry.name)) continue;
    const relative = path.posix.join(relativeDir, entry.name);
    if (entry.isDirectory()) {
      await walk(relative, files);
    } else if (entry.isFile()) {
      files.push(relative);
    }
  }
}

export async function computeSourceFingerprint() {
  const files = [];
  for (const dir of FINGERPRINT_DIRS) await walk(dir, files);
  for (const file of FINGERPRINT_FILES) {
    try {
      const stat = await fs.stat(path.join(ROOT, file));
      if (stat.isFile()) files.push(file);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
  files.sort();
  const hash = createHash('sha256');
  for (const file of files) {
    const content = await fs.readFile(path.join(ROOT, file));
    hash.update(file);
    hash.update('\0');
    hash.update(content);
    hash.update('\0');
  }
  return { fingerprint: hash.digest('hex'), fileCount: files.length };
}

export function validateState(state) {
  const errors = [];
  if (state === null || typeof state !== 'object' || Array.isArray(state)) {
    return ['STATE must be a JSON object'];
  }
  if (state.schemaVersion !== 1) errors.push('schemaVersion must be 1');
  if (!['in_progress', 'blocked', 'complete'].includes(state.status)) {
    errors.push('status must be in_progress, blocked or complete');
  }
  if (typeof state.activeTaskId !== 'string' || state.activeTaskId.length === 0) {
    errors.push('activeTaskId must be a non-empty string');
  }
  if (state.lastCompletedTaskId !== null && typeof state.lastCompletedTaskId !== 'string') {
    errors.push('lastCompletedTaskId must be a string or null');
  }
  if (typeof state.nextAction !== 'string' || state.nextAction.trim().length < 8) {
    errors.push('nextAction must be a specific sentence (>= 8 characters)');
  }
  if (state.workIntent === null || typeof state.workIntent !== 'object') {
    errors.push('workIntent must be an object');
  } else {
    if (typeof state.workIntent.summary !== 'string') errors.push('workIntent.summary must be a string');
    if (!Array.isArray(state.workIntent.files) || !state.workIntent.files.every((f) => typeof f === 'string')) {
      errors.push('workIntent.files must be a string array');
    }
  }
  for (const key of ['workingFiles', 'knownFailures', 'processes', 'verification']) {
    if (!Array.isArray(state[key])) errors.push(`${key} must be an array`);
  }
  if (state.sourceFingerprint !== null && !/^[a-f0-9]{64}$/.test(String(state.sourceFingerprint))) {
    errors.push('sourceFingerprint must be null or a 64-character hex digest');
  }
  if (typeof state.updatedAt !== 'string' || Number.isNaN(Date.parse(state.updatedAt))) {
    errors.push('updatedAt must be an ISO timestamp');
  }
  return errors;
}

function renderHandoff(state, fingerprint, fileCount) {
  const lines = [];
  lines.push('# ECE Accounting Mockup — Handoff');
  lines.push('');
  lines.push('> Generated by `npm run checkpoint` from `docs/STATE.json`. Do not edit by hand.');
  lines.push('');
  lines.push(`- Status: **${state.status}**`);
  lines.push(`- Active task: **${state.activeTaskId}**`);
  lines.push(`- Last completed task: ${state.lastCompletedTaskId ?? '—'}`);
  lines.push(`- Updated: ${state.updatedAt}`);
  lines.push(`- Source fingerprint: \`${fingerprint}\` (${fileCount} files)`);
  lines.push('');
  lines.push('## Next action');
  lines.push('');
  lines.push(state.nextAction);
  lines.push('');
  lines.push('## Current edit intent');
  lines.push('');
  lines.push(state.workIntent.summary);
  if (state.workIntent.files.length > 0) {
    lines.push('');
    for (const file of state.workIntent.files) lines.push(`- \`${file}\``);
  }
  lines.push('');
  lines.push('## Working files');
  lines.push('');
  if (state.workingFiles.length === 0) lines.push('None recorded.');
  for (const item of state.workingFiles) {
    lines.push(typeof item === 'string' ? `- ${item}` : `- \`${item.path}\`: ${item.note ?? ''}`);
  }
  lines.push('');
  lines.push('## Known failures');
  lines.push('');
  if (state.knownFailures.length === 0) lines.push('None recorded.');
  for (const item of state.knownFailures) {
    lines.push(typeof item === 'string' ? `- ${item}` : `- ${item.summary ?? JSON.stringify(item)}`);
  }
  lines.push('');
  lines.push('## Processes / environment notes');
  lines.push('');
  if (state.processes.length === 0) lines.push('None recorded.');
  for (const item of state.processes) {
    lines.push(typeof item === 'string' ? `- ${item}` : `- ${item.summary ?? JSON.stringify(item)}`);
  }
  lines.push('');
  lines.push('## Verification history');
  lines.push('');
  if (state.verification.length === 0) lines.push('None recorded.');
  for (const item of state.verification) {
    if (typeof item === 'string') {
      lines.push(`- ${item}`);
      continue;
    }
    const at = item.capturedAt ?? item.at ?? '';
    const outcome = item.exitCode === 0 ? 'pass' : item.status ?? `exit ${item.exitCode}`;
    const fp = item.sourceFingerprint ? ` @ ${String(item.sourceFingerprint).slice(0, 12)}` : '';
    lines.push(`- \`${item.command}\` — ${outcome}${at ? ` (${at})` : ''}${fp}${item.artifact ? ` → \`${item.artifact}\`` : ''}`);
  }
  lines.push('');
  lines.push('## Read before resuming');
  lines.push('');
  lines.push('1. `AGENTS.md`, `tasks/todo.md`, this handoff and `docs/STATE.json`.');
  lines.push('2. Inspect actual files and rerun the focused check for the interrupted task.');
  lines.push('3. Repair partial work, record actual results, then continue the next dependency.');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const raw = await fs.readFile(STATE_PATH, 'utf8');
  let state;
  try {
    state = JSON.parse(raw);
  } catch (error) {
    fail(`docs/STATE.json is not valid JSON: ${error.message}`);
  }
  const errors = validateState(state);
  if (errors.length > 0) fail(`invalid STATE.json:\n- ${errors.join('\n- ')}`);

  const { fingerprint, fileCount } = await computeSourceFingerprint();
  const nextState = {
    ...state,
    sourceFingerprint: fingerprint,
    updatedAt: new Date().toISOString(),
  };
  const serialized = `${JSON.stringify(nextState, null, 2)}\n`;
  const tempPath = `${STATE_PATH}.${process.pid}.tmp`;
  await fs.writeFile(tempPath, serialized, 'utf8');
  await fs.rename(tempPath, STATE_PATH);

  const handoff = renderHandoff(nextState, fingerprint, fileCount);
  const handoffTemp = `${HANDOFF_PATH}.${process.pid}.tmp`;
  await fs.writeFile(handoffTemp, handoff, 'utf8');
  await fs.rename(handoffTemp, HANDOFF_PATH);

  let todoDone = 0;
  let todoTotal = 0;
  try {
    const todo = await fs.readFile(TODO_PATH, 'utf8');
    for (const line of todo.split('\n')) {
      if (/^\s*- \[[ xX]\]/.test(line)) {
        todoTotal += 1;
        if (/^\s*- \[[xX]\]/.test(line)) todoDone += 1;
      }
    }
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }

  console.log(`checkpoint ok: ${fingerprint.slice(0, 16)}… over ${fileCount} files`);
  console.log(`state: ${path.relative(ROOT, STATE_PATH)}  handoff: ${path.relative(ROOT, HANDOFF_PATH)}`);
  if (todoTotal > 0) console.log(`tasks/todo.md: ${todoDone}/${todoTotal} checked items`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
